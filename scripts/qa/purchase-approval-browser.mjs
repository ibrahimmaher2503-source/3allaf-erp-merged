import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const base = process.env.QA_BROWSER_URL;
if (!base || new URL(base).hostname !== '127.0.0.1' || !process.env.QA_STORAGE?.startsWith('/tmp/rajeh-qa-mariadb.')) throw new Error('Disposable loopback runtime required');
const f = JSON.parse(readFileSync(process.env.QA_STORAGE + '/purchase-browser.json', 'utf8'));
const browser = await chromium.launch({ headless: true, executablePath: process.env.QA_CHROMIUM, args: ['--no-sandbox'] });
const errors = [];
const check = (ok, message) => { if (!ok) throw new Error(message); console.log('PASS ' + message); };
try {
    const page = await browser.newPage({viewport:{width:1280,height:900}});
    page.on('pageerror', e => errors.push(e.message));
    page.on('response', r => { if (r.status() >= 500) errors.push('HTTP '+r.status()); });
    page.on('dialog', dialog => dialog.accept());
    const open = async path => { const r = await page.goto(base+path,{waitUntil:'networkidle'});check(r.status() === 200,path+' HTTP 200'); };
    await open('/login');
    await page.locator('input[name=username]').fill(f.username);
    await page.locator('input[name=password]').fill(f.password);
    await Promise.all([page.waitForURL(u => !u.pathname.endsWith('/login')),page.locator('[data-test=login-button]').click()]);
    await page.evaluate(async () => { const token=document.querySelector('meta[name=csrf-token]').content;await fetch('/locale',{method:'POST',headers:{'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams({_token:token,locale:'ar'})}); });
    await open('/purchasing/invoices');
    check(await page.locator('html').getAttribute('dir') === 'rtl','Arabic RTL');
    check(!/التوزيع الإلزامي|اعتماد وترحيل|اعتماد وتوزيع/.test(await page.locator('body').innerText()),'No obsolete workflow wording');
    await page.locator(`[wire\\:click="openReceivingReview(${f.invoice})"]`).click();
    const quantity = page.locator(`[wire\\:model="receivedQuantities.${f.line}"]`);
    await quantity.waitFor();
    check(await quantity.inputValue() === '1000','Original accepted quantity loaded');
    await quantity.fill('900');
    await page.locator(`form[wire\\:submit="approveInvoice(${f.invoice})"] button[type=submit]`).click();
    await quantity.waitFor({state:'hidden'});
    await open('/purchasing/quantity-differences');
    const row = page.locator('tbody tr').filter({hasText:'منتج فحص الاستلام'});
    check(await row.count() === 1,'One shortage report row');
    for (const value of ['1,000','900','100']) check((await row.innerText()).includes(value) || (value === '1,000' && (await row.innerText()).includes('1000')),'Report quantity '+value);
    check((await row.innerText()).includes('مخزن الدقي A'),'Receiving destination preserved');
    await page.setViewportSize({width:390,height:844});
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1),'Mobile document has no horizontal overflow');
    await page.screenshot({path:process.env.QA_STORAGE+'/purchase-shortage-ar-mobile.png',fullPage:true});
    await page.setViewportSize({width:1280,height:900});
    await open(`/catalog/products/${f.product}/edit`);
    const model=page.locator('[wire\\:model="productForm.model_number"]');
    check(await model.getAttribute('required') === null,'Model number has no required attribute');
    await model.fill('');
    const saved=page.waitForResponse(r => r.url().includes('/livewire-') && r.request().method()==='POST');
    await page.locator('form[wire\\:submit="save"] button[type=submit]').click();
    check((await saved).status()===200,'Blank model final save');
    await open(`/catalog/products/${f.product}/edit`);
    check(await model.inputValue() === '','Blank model persists');
    await page.evaluate(async () => { const token=document.querySelector('meta[name=csrf-token]').content;await fetch('/locale',{method:'POST',headers:{'Content-Type':'application/x-www-form-urlencoded'},body:new URLSearchParams({_token:token,locale:'en'})}); });
    await open('/purchasing/quantity-differences');
    check(await page.locator('html').getAttribute('dir') === 'ltr','English LTR');
    check((await page.locator('body').innerText()).includes('Quantity differences'),'English report labels');
    check(errors.length===0,'No browser errors: '+errors.join('; '));
} finally { await browser.close(); }
